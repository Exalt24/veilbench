"""Command line: `veilbench <command>`. Every number in the README comes from one of these commands writing a file under docs/test-runs/."""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

from veilbench.corpus.generate import corpus_sha, corpus_stats, generate_corpus
from veilbench.detect.base import merge_spans
from veilbench.detect.pipeline import build_component
from veilbench.evaluation import experiments as E
from veilbench.evaluation.benchmark import run_benchmark
from veilbench.evaluation.metrics import verbatim_leak
from veilbench.structured import StructuredAnonymizer
from veilbench.transform.ops import TECHNIQUES, Transformer


def _write(out: Path, name: str, data: dict) -> None:
    out.mkdir(parents=True, exist_ok=True)
    (out / name).write_text(json.dumps(data, indent=1), encoding="utf-8")
    print(f"wrote {out / name}")


def _detector(models: bool = False):
    rules, stat = build_component("rules"), build_component("stat")
    comps = [rules, stat]
    if models:
        comps.append(build_component("gliner"))

    def detect(text: str):
        spans = []
        for c in comps:
            spans += c.detect(text)
        return spans

    return detect


def cmd_demo(args) -> int:
    """A short real run for the README recording: one generated record through all five techniques."""
    sys.stdout.reconfigure(encoding="utf-8")
    det = _detector()
    # the first generated ticket that is short, has several identifier types and is found exactly: the recording should show the idea, not a miss
    for rec in generate_corpus(300, 7):
        if rec.kind != "ticket" or rec.meta["lang"] != "en" or "obfuscated" in rec.slices or len(rec.text) > 430 or len({s.label for s in rec.spans}) < 5:
            continue
        spans = merge_spans(det(rec.text))
        if {(s.start, s.end, s.label) for s in spans} == {(s.start, s.end, s.label) for s in rec.spans}:
            break
    print("\033[1mRAW RECORD\033[0m  (generated by code; every identifier below is made up)")
    print(rec.text.strip(), "\n")
    print(f"detected {len(spans)} identifiers, all of them: " + ", ".join(s.label for s in spans), "\n")
    for t in TECHNIQUES:
        out = Transformer(t).apply(rec.text, spans)
        leaked = len(verbatim_leak(rec, out))
        print(f"\033[1m{t.upper()}\033[0m  (identifiers still readable: {leaked})")
        print(out.strip(), "\n")
        time.sleep(args.pause)
    return 0


def cmd_anonymize(args) -> int:
    text = Path(args.file).read_text(encoding="utf-8") if args.file != "-" else sys.stdin.read()
    res = StructuredAnonymizer(_detector(args.models), Transformer(args.technique)).run(text)
    sys.stdout.write(res.text)
    print(f"\n[{res.mode}: {res.changed_leaves} values changed, {res.by_hint} of them only because of a field name or a column vote]", file=sys.stderr)
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="veilbench")
    sub = ap.add_subparsers(dest="cmd", required=True)
    out_default = Path("docs/test-runs")

    p = sub.add_parser("corpus", help="print the generated corpus statistics")
    p.add_argument("--n", type=int, default=800)
    p.add_argument("--seed", type=int, default=7)

    p = sub.add_parser("benchmark", help="detector configurations over the corpus")
    p.add_argument("--n", type=int, default=800)
    p.add_argument("--seed", type=int, default=7)
    p.add_argument("--out", type=Path, default=out_default)
    p.add_argument("--work", type=Path, default=Path(".work"))
    p.add_argument("--configs", nargs="*")
    p.add_argument("--max-seconds", type=float, default=None, help="stop a component after this long; run the command again to resume")
    p.add_argument("--no-llm", action="store_true")
    p.add_argument("--split", choices=["eval", "ood"], default="eval")
    p.add_argument("--llm-records", type=int, default=300)

    for name in ("privacy", "utility", "xdoc", "robustness", "techniques"):
        q = sub.add_parser(name)
        q.add_argument("--out", type=Path, default=out_default)

    p = sub.add_parser("demo")
    p.add_argument("--pause", type=float, default=0.0)
    p = sub.add_parser("anonymize", help="anonymize a file (JSON, delimited or plain text) or - for stdin")
    p.add_argument("file")
    p.add_argument("--technique", choices=TECHNIQUES, default="pseudonymize")
    p.add_argument("--models", action="store_true", help="add the GLiNER model to rules and the statistical detector")

    a = ap.parse_args(argv)
    if a.cmd == "corpus":
        recs = generate_corpus(a.n, a.seed)
        print(json.dumps({**corpus_stats(recs), "sha256": corpus_sha(recs)}, indent=1))
    elif a.cmd == "benchmark":
        r = run_benchmark(a.n, a.seed, a.out, a.work, a.configs, a.max_seconds, not a.no_llm, a.split, a.llm_records)
        if r.get("incomplete"):
            print(json.dumps(r))
            return 3
        print((a.out / ("benchmark.md" if a.split == "eval" else f"benchmark_{a.split}.md")).read_text(encoding="utf-8"))
    elif a.cmd == "privacy":
        _write(a.out, "privacy.json", E.privacy_report())
    elif a.cmd == "utility":
        det = _detector()
        _write(a.out, "utility.json", E.utility_report({"rules+stat": det}))
    elif a.cmd == "xdoc":
        _write(a.out, "cross_document_names.json", E.xdoc_report())
    elif a.cmd == "techniques":
        _write(a.out, "techniques.json", {"rows": E.technique_table(generate_corpus(800, 7))})
    elif a.cmd == "robustness":
        recs = generate_corpus(800, 7)
        rules_only = build_component("rules")
        _write(a.out, "robustness.json", {"rules only": E.robustness_report(recs, rules_only.detect), "rules + statistical model": E.robustness_report(recs, _detector())})
    elif a.cmd == "demo":
        return cmd_demo(a)
    elif a.cmd == "anonymize":
        return cmd_anonymize(a)
    return 0


if __name__ == "__main__":
    sys.exit(main())
