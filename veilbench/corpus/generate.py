def ticket_corpus(n_customers: int = 250, n_tickets: int = 1200, seed: int = 21) -> list[Record]:
    """English tickets from a pool of repeat customers: a category label for a classifier, and a customer key for an aggregate query."""
    rng = random.Random(seed)
    customers = [P.make_person(rng, ["en", "es", "ph"], uid=i) for i in range(n_customers)]
    out: list[Record] = []
    for i in range(n_tickets):
        p = customers[min(int(rng.expovariate(1 / (n_customers / 3.0))), n_customers - 1)] if rng.random() < 0.5 else rng.choice(customers)
        q = rng.choice(customers)
        tb = TB()
        ctx = Ctx(rng, tb, p, q, "en", False, False, set())
        cat = rng.choice(list(CATEGORIES))
        # a second, unrelated sentence from another category makes the label noisier than a keyword lookup
        tb.t("")
        ctx.fill(rng.choice(["Hi, this is {FULL}.", "Hello, {PERSON} here.", "Dear team, {FULL} writing."]))
        tb.t(" " + rng.choice(CATEGORIES[cat]) + " ")
        if rng.random() < 0.45:
            other = rng.choice([c for c in CATEGORIES if c != cat])
            tb.t(rng.choice(CATEGORIES[other]) + " ")
        for s in rng.sample(ID_EN[:6], 2):
            ctx.fill(s)
            tb.t(" ")
        tb.t("\nAccount email: ")
        ctx.slot("EMAIL")  # the join key the aggregate query uses: one stable value per customer
        tb.t("\n")
        ctx.fill(rng.choice(["Thanks, {FIRST}", "Regards,\n{FULL}"]))
        out.append(Record(id=f"t{i:05d}", kind="ticket", text=tb.text(), spans=sorted(tb.spans), negatives=[], slices=["ticket"],
                          meta={"category": cat, "customer": p.uid}))
    return out
