"""A seeded generator of labelled records: tickets, call transcripts, JSON with schema drift, CSV, log lines and file listings.

Every identifier is generated by code (people.py). The ground truth is recorded while the text is built,
so each span's offsets are exact by construction, never found afterwards by searching.

Two splits share the generator but not all of its parts. `split="train"` uses only some cultures and
some templates and no obfuscation; `split="eval"` uses everything. A detector trained on `train` is therefore
measured on `eval` records with names, phrasings and forms it has never seen.
"""
from __future__ import annotations

import hashlib
import json
import random
import re
from dataclasses import dataclass

from veilbench.corpus import names as N
from veilbench.corpus import people as P
from veilbench.schema import Record, Span

# ---------------------------------------------------------------- builder


class TB:
    """Text builder that records ground truth offsets as it appends."""

    def __init__(self) -> None:
        self.parts: list[str] = []
        self.pos = 0
        self.spans: list[Span] = []
        self.negs: list[Span] = []

    def t(self, s: str) -> None:
        self.parts.append(s)
        self.pos += len(s)

    def e(self, label: str, value: str, canon: str = "") -> None:
        start = self.pos
        self.t(value)
        self.spans.append(Span(start, self.pos, label, "gt", canon or value))

    def n(self, value: str) -> None:
        start = self.pos
        self.t(value)
        self.negs.append(Span(start, self.pos, "NEG", "gt"))

    def text(self) -> str:
        return "".join(self.parts)

    def embed_json_string(self, sub: "TB") -> None:
        """Append `sub` as a JSON string literal, shifting its spans for the backslashes the escaping adds."""
        raw = sub.text()
        escaped = json.dumps(raw, ensure_ascii=False)  # includes the surrounding quotes
        base = self.pos + 1

        def shift(sp: Span) -> Span:
            before = raw[:sp.start]
            add_start = before.count('"') + before.count("\\")
            inner = raw[sp.start:sp.end]
            add_inner = inner.count('"') + inner.count("\\")
            return Span(base + sp.start + add_start, base + sp.end + add_start + add_inner, sp.label, sp.source, sp.canon)

        self.spans.extend(shift(s) for s in sub.spans)
        self.negs.extend(shift(s) for s in sub.negs)
        self.t(escaped)


@dataclass
class Ctx:
    rng: random.Random
    tb: TB
    p: P.Person
    q: P.Person
    lang: str = "en"
    obf: bool = False
    train: bool = False
    tags: set | None = None

    def tag(self, name: str) -> None:
        if self.tags is not None:
            self.tags.add(name)

    def _maybe_obf(self) -> bool:
        return self.obf and self.rng.random() < 0.8 and not self.train

    def slot(self, name: str) -> None:
        tb, rng, p = self.tb, self.rng, self.p
        if name == "PERSON":
            tb.e("PERSON", P.person_surface(rng, p, None, self.lang))
        elif name == "FULL":
            tb.e("PERSON", p.full)
        elif name == "FIRST":
            tb.e("PERSON", p.first)
        elif name == "TITLED":
            tb.e("PERSON", P.person_surface(rng, p, "title_last", self.lang))
        elif name == "LASTFIRST":
            tb.e("PERSON", P.person_surface(rng, p, "last_first", self.lang))
        elif name == "PERSON2":
            tb.e("PERSON", P.person_surface(rng, self.q, rng.choice(["full", "full", "first", "title_last"]), self.lang))
        elif name == "EMAIL":
            o = self._maybe_obf()
            s, c = P.email_surface(rng, p, o)
            if o:
                self.tag("obfuscated")
            tb.e("EMAIL", s, c)
        elif name == "PHONE":
            o = self._maybe_obf()
            s, c = P.phone_surface(rng, p, o)
            if o:
                self.tag("obfuscated")
            tb.e("PHONE", s, c)
        elif name == "ADDRESS":
            tb.e("ADDRESS", p.address)
        elif name == "ID":
            o = self._maybe_obf()
            s, c = P.id_surface(rng, p, o)
            if o:
                self.tag("obfuscated")
            tb.e("NATIONAL_ID", s, c)
        elif name == "CARD":
            o = self._maybe_obf()
            s, c = P.card_surface(rng, p, o)
            if o:
                self.tag("obfuscated")
            tb.e("CREDIT_CARD", s, c)
        elif name == "IBAN":
            iban = p.iban
            tb.e("IBAN", rng.choice([iban, " ".join(iban[i:i + 4] for i in range(0, len(iban), 4))]), iban)
        elif name == "DOB":
            s, c = P.dob_surface(rng, p, self.lang)
            tb.e("DATE_OF_BIRTH", s, c)
        elif name == "IP":
            tb.e("IP_ADDRESS", p.ip)
        elif name == "PASSWORD":
            tb.e("PASSWORD", P.make_password(rng))
        elif name == "KEY":
            lab, v = P.make_secret(rng, rng.choice(["stripe", "aws", "github", "slack", "google", "openai", "gitlab", "sendgrid", "hf", "generic"]))
            tb.e(lab, v)
        elif name == "JWT":
            lab, v = P.make_secret(rng, "jwt")
            tb.e(lab, v)
        elif name.startswith("NEG_"):
            tb.n(P.make_negative(rng, name[4:].lower()))
        else:
            raise KeyError(name)

    def fill(self, template: str) -> None:
        for piece in re.split(r"(\{[A-Z0-9_]+\})", template):
            if piece.startswith("{") and piece.endswith("}"):
                self.slot(piece[1:-1])
            elif piece:
                self.tb.t(piece)


