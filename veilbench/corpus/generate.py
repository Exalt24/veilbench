def _ticket(ctx: Ctx, category: str, lang: str) -> None:
    rng = ctx.rng
    if lang == "en":
        opens = OPEN_EN + ([] if ctx.train else OPEN_EN_EVAL)
        ids_ = ID_EN + ([] if ctx.train else ID_EN_EVAL)
        body = rng.choice(CATEGORIES[category])
        closes, negs = CLOSE_EN, NEG_SENT
    elif lang == "es":
        opens, ids_, closes, negs = OPEN_ES, ID_ES, CLOSE_ES, NEG_SENT_ES
        body = rng.choice(CATEGORY_GENERIC_ES)
    else:
        opens, ids_, closes, negs = OPEN_TL, ID_TL, CLOSE_TL, NEG_SENT_TL
        body = rng.choice(CATEGORY_GENERIC_TL)
    ctx.fill(rng.choice(opens))
    ctx.tb.t(" " + body + " ")
    sents = rng.sample(ids_, rng.randint(2, 4))
    if rng.random() < 0.8:
        sents += rng.sample(negs, 1 if rng.random() < 0.6 else min(2, len(negs)))
    rng.shuffle(sents)
    for s in sents:
        ctx.fill(s)
        ctx.tb.t(" ")
    ctx.fill(rng.choice(closes))


def _transcript(ctx: Ctx) -> None:
    rng = ctx.rng
    ctx.obf = True
    lines = [
        ("Agent", ["Thank you for calling support, how can I help?", "Support line, how can I help you today?"]),
        ("Caller", ["Hi, my name is {PERSON} and I need to check an order.", "Hello, this is {FULL}, I am calling about a charge."]),
        ("Agent", ["Sure. Can I get a number to reach you on?", "No problem. What phone number is on the account?"]),
        ("Caller", ["It is {PHONE}.", "Yes, {PHONE}."]),
        ("Agent", ["And the email for the account?", "Which email did you sign up with?"]),
        ("Caller", ["{EMAIL}.", "It is {EMAIL}, I think."]),
    ]
    if rng.random() < 0.5:
        lines += [("Agent", ["Thanks. For security, can you confirm your date of birth?"]), ("Caller", ["{DOB}.", "It is {DOB}."])]
    else:
        lines += [("Agent", ["Can I have the delivery address, please?"]), ("Caller", ["{ADDRESS}.", "That is {ADDRESS}, and the reference is {NEG_ORDER}."])]
    for who, opts in lines:
        ctx.tb.t(f"{who}: ")
        ctx.fill(rng.choice(opts))
        ctx.tb.t("\n")
    if rng.random() < 0.5:
        ctx.tb.t("Caller: ")
        ctx.fill(rng.choice(["The card is {CARD}.", "My ID is {ID}."]))
        ctx.tb.t("\n")


# ---------------------------------------------------------------- JSON with drift


def _json_val(tb: TB, v, rng: random.Random, indent: int | None, level: int) -> None:
    nl = "\n" + " " * (indent * (level + 1)) if indent else ""
    nl_end = "\n" + " " * (indent * level) if indent else ""
    sep = ", " if not indent else ","
    if isinstance(v, dict):
        tb.t("{")
        items = list(v.items())
        for i, (k, val) in enumerate(items):
            tb.t(nl + json.dumps(k) + ": ")
            _json_val(tb, val, rng, indent, level + 1)
            if i < len(items) - 1:
                tb.t(sep.rstrip(" ") if indent else ", ")
        tb.t(nl_end + "}")
    elif isinstance(v, list):
        tb.t("[")
        for i, val in enumerate(v):
            tb.t(nl)
            _json_val(tb, val, rng, indent, level + 1)
            if i < len(v) - 1:
                tb.t(sep.rstrip(" ") if indent else ", ")
        tb.t(nl_end + "]")
    elif isinstance(v, tuple):  # ("ent", label, value, canon) | ("neg", value) | ("parts", [...]) | ("json", sub TB)
        kind = v[0]
        if kind == "ent":
            tb.t('"')
            tb.e(v[1], v[2], v[3] if len(v) > 3 else "")
            tb.t('"')
        elif kind == "neg":
            tb.t('"')
            tb.n(v[1])
            tb.t('"')
        elif kind == "parts":
            tb.t('"')
            for part in v[1]:
                if isinstance(part, tuple):
                    if part[0] == "e":
                        tb.e(part[1], part[2], part[3] if len(part) > 3 else "")
                    else:
                        tb.n(part[1])
                else:
                    tb.t(part)
            tb.t('"')
        elif kind == "json":
            tb.embed_json_string(v[1])
    elif isinstance(v, str):
        tb.t(json.dumps(v, ensure_ascii=False))
    elif v is None:
        tb.t("null")
    elif isinstance(v, bool):
        tb.t("true" if v else "false")
    else:
        tb.t(str(v))


def _note_parts(ctx: Ctx, templates: list[str]) -> list:
    """A free text value assembled through a scratch TB, returned as parts a JSON emitter can place."""
    sub = TB()
    c = Ctx(ctx.rng, sub, ctx.p, ctx.q, ctx.lang, ctx.obf, ctx.train, ctx.tags)
    for t in templates:
        c.fill(t)
        sub.t(" ")
    parts: list = []
    cursor = 0
    text = sub.text().rstrip()
    marks = sorted([(s.start, s.end, "e", s) for s in sub.spans] + [(s.start, s.end, "n", s) for s in sub.negs])
    for a, b, kind, s in marks:
        if a > len(text):
            continue
        parts.append(text[cursor:a])
        parts.append(("e", s.label, text[a:b], s.canon) if kind == "e" else ("n", text[a:b]))
        cursor = b
    parts.append(text[cursor:])
    return parts


def _contains_quote(parts: list) -> bool:
    return any(('"' in x or "\\" in x) if isinstance(x, str) else ('"' in x[2] or "\\" in x[2] if x[0] == "e" else '"' in x[1]) for x in parts)


def _json_record(ctx: Ctx, variant: int, unexpected_only: bool, with_secret: bool) -> None:
    rng, p = ctx.rng, ctx.p
    tb = ctx.tb
    o = ctx._maybe_obf()
    es, ec = P.email_surface(rng, p, o)
    ps, pc = P.phone_surface(rng, p, o)
    if o:
        ctx.tag("obfuscated")
    name = ("ent", "PERSON", p.full)
    email = ("ent", "EMAIL", es, ec)
    phone = ("ent", "PHONE", ps, pc)
    addr = ("ent", "ADDRESS", p.address)
    redacted = "***"
    if unexpected_only:
        name = email = phone = addr = redacted
        cust_id = rng.randint(10_000, 99_999)
    else:
        cust_id = rng.randint(10_000, 99_999)
    if variant == 0:
        body = {"id": cust_id, "name": name, "email": email, "phone": phone, "address": addr}
    elif variant == 1:
        body = {"id": cust_id, "customer": {"full_name": name, "contact": {"email": email, "mobile": phone}}, "shipping": {"addr": addr}}
    elif variant == 2:
        body = {"customerId": cust_id, "fullName": name, "eMail": email, "tel": phone, "shipTo": addr}
    elif variant == 3:
        body = {"f0": cust_id, "f1": name, "f2": email, "f3": phone, "f4": addr}
    elif variant == 4:
        body = {"id": cust_id, "attributes": [{"k": "nm", "v": name}, {"k": "mail", "v": email}, {"k": "msisdn", "v": phone}, {"k": "loc", "v": addr}]}
    else:
        body = {"Id": cust_id, "Nme": name, "emaill": email, "Phne": phone, "Adr": addr, "extra_unknown_block": {"flags": [1, 0, 1]}}
    body["created"] = ("neg", P.make_negative(rng, "epoch"))
    body["trace_id"] = ("neg", P.make_negative(rng, "uuid"))
    body["build"] = ("neg", P.make_negative(rng, "version"))
    place_unexpected = unexpected_only or rng.random() < 0.55
    if place_unexpected:
        ctx.tag("unexpected_field")
        pool = ["Customer called, {PERSON} asked for a callback on {PHONE}.", "Escalated by {PERSON2}; contact {EMAIL}.", "Note: delivery to {ADDRESS} failed twice.", "Verified ID {ID} on the phone.", "Birth date given: {DOB}."]
        for _ in range(8):
            parts = _note_parts(ctx, rng.sample(pool, rng.randint(1, 2)))
            if not _contains_quote(parts):
                break
        body["notes"] = ("parts", parts)
        if rng.random() < 0.5:
            parts2 = _note_parts(ctx, ["retry from {IP} for {EMAIL}"])
            body["meta"] = {"debug": ("parts", parts2), "attempt": 2}
    if with_secret:
        ctx.tag("unexpected_field")
        sub = TB()
        lab, val = P.make_secret(rng, rng.choice(["stripe", "aws", "github", "generic", "openai"]))
        inner = {"endpoint": "https://api.vendor.example/v2/sync", "key": ("ent", lab, val), "retries": 3}
        _json_val(sub, inner, rng, None, 0)
        body["payload"] = ("json", sub)
        if rng.random() < 0.5:
            jl, jv = P.make_secret(rng, "jwt")
            body["headers"] = {"Authorization": ("parts", ["Bearer ", ("e", jl, jv)])}
    indent = rng.choice([None, 2, 4])
    _json_val(tb, body, rng, indent, 0)


