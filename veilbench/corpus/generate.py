KIND_WEIGHTS = [("ticket", 0.36), ("transcript", 0.08), ("json", 0.22), ("csv", 0.10), ("log", 0.14), ("filename", 0.10)]
CULTURE_WEIGHTS = {"en": 0.28, "es": 0.14, "ph": 0.2, "de": 0.05, "in": 0.08, "zh": 0.08, "ar": 0.06, "vn": 0.05, "ng": 0.06}


def _choose(rng: random.Random, weights: list[tuple[str, float]]) -> str:
    r = rng.random() * sum(w for _, w in weights)
    for k, w in weights:
        r -= w
        if r <= 0:
            return k
    return weights[-1][0]


def make_record(rng: random.Random, idx: int, split: str = "eval", kind: str | None = None) -> Record:
    train = split == "train"
    cultures = N.TRAIN_CULTURES if train else [c for c, w in CULTURE_WEIGHTS.items() for _ in range(int(w * 100))]
    p = P.make_person(rng, cultures, uid=idx)
    q = P.make_person(rng, cultures, uid=idx + 1_000_000)
    from veilbench.corpus import ood
    kind = kind or _choose(rng, ood.OOD_KINDS if split == "ood" else KIND_WEIGHTS)
    lang = "en"
    if kind == "ticket":
        r = rng.random()
        lang = "en" if (r < 0.7 or (train and r < 0.85)) else "es" if r < 0.85 else "tl"
        if train and lang == "tl":
            lang = "es"
    tags: set = set()
    tb = TB()
    obf = (not train) and rng.random() < 0.13
    ctx = Ctx(rng, tb, p, q, lang, obf, train, tags)
    category = rng.choice(list(CATEGORIES))
    drift_variant = 0
    if kind == "ticket":
        _ticket(ctx, category, lang)
    elif kind == "transcript":
        _transcript(ctx)
    elif kind == "json":
        drift_variant = rng.randint(0, 2) if train else rng.randint(0, 5)
        unexpected_only = rng.random() < 0.35
        _json_record(ctx, drift_variant, unexpected_only, with_secret=rng.random() < 0.4)
        if drift_variant >= 1:
            tags.add("drift")
    elif kind in ood.BUILDERS:
        ood.BUILDERS[kind](ctx)
    elif kind == "csv":
        drift_variant = rng.randint(0, 2) if train else rng.randint(0, 4)
        _csv_record(ctx, drift_variant, rng.random() < 0.3)
        if drift_variant >= 2:
            tags.add("drift")
    elif kind == "log":
        drift_variant = rng.randint(0, 1)
        _log_record(ctx, drift_variant)
    else:
        _filename_record(ctx, drift_variant)
    text = tb.text()
    slices = [kind]
    if split == "ood":
        slices.append("ood")
    if kind in ("ticket", "transcript") and not tags and lang == "en":
        slices.append("clean")
    if p.culture not in ("en",) or lang != "en":
        slices.append("non_english")
    if tb.negs:
        slices.append("hard_negative")
    slices += sorted(tags)
    if obf and "obfuscated" not in tags and kind in ("ticket", "transcript"):
        pass
    spans = sorted(tb.spans)
    return Record(id=f"r{idx:05d}", kind=kind, text=text, spans=spans, negatives=sorted(tb.negs), slices=slices,
                  meta={"category": category if kind == "ticket" else "", "culture": p.culture, "lang": lang, "variant": drift_variant, "person": p.uid})


def generate_corpus(n: int = 800, seed: int = 7, split: str = "eval", kind: str | None = None) -> list[Record]:
    rng = random.Random(seed)
    return [make_record(rng, i, split, kind) for i in range(n)]


def corpus_sha(records: list[Record]) -> str:
    h = hashlib.sha256()
    for r in records:
        h.update(r.text.encode("utf-8"))
        h.update(json.dumps([(s.start, s.end, s.label) for s in r.spans]).encode())
    return h.hexdigest()


def corpus_stats(records: list[Record]) -> dict:
    from collections import Counter
    spans = Counter(s.label for r in records for s in r.spans)
    slices = Counter(sl for r in records for sl in r.slices)
    return {"records": len(records), "spans": sum(spans.values()), "negatives": sum(len(r.negatives) for r in records),
            "spans_by_type": dict(sorted(spans.items())), "records_by_slice": dict(sorted(slices.items()))}


